// Generates the app icon from a 16x16 pixel design (no image libraries):
//   build/icon.png      256x256, used by electron-builder for the .exe/installer
//   src/main/icon.ts    16/32/256 px PNGs as base64, used for the tray and window
// Run: node scripts/make-icons.mjs
import { deflateSync } from "node:zlib";
import { writeFileSync, mkdirSync } from "node:fs";

const ART = [
  "################",
  "#..............#",
  "#.############.#",
  "#.#..........#.#",
  "#.#..##......#.#",
  "#.#..##......#.#",
  "#.#..##......#.#",
  "#.#..##......#.#",
  "#.#..##......#.#",
  "#.#..##......#.#",
  "#.#..######..#.#",
  "#.#..######..#.#",
  "#.#..........#.#",
  "#.############.#",
  "#..............#",
  "################",
];
const FG = [0xe6, 0xe6, 0xe6, 0xff];
const BG = [0x00, 0x00, 0x00, 0xff];

const CRC = new Int32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c;
});
function crc32(buf) {
  let c = -1;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

function png(size) {
  const scale = size / 16;
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0; // filter: none
    for (let x = 0; x < size; x++) {
      const on = ART[Math.floor(y / scale)][Math.floor(x / scale)] === "#";
      Buffer.from(on ? FG : BG).copy(raw, y * (size * 4 + 1) + 1 + x * 4);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

mkdirSync("build", { recursive: true });
writeFileSync("build/icon.png", png(256));
writeFileSync(
  "src/main/icon.ts",
  `// Generated by scripts/make-icons.mjs. Do not edit by hand.\n` +
    `export const ICON_16 = "${png(16).toString("base64")}";\n` +
    `export const ICON_32 = "${png(32).toString("base64")}";\n` +
    `export const ICON_256 = "${png(256).toString("base64")}";\n`,
);
console.log("wrote build/icon.png and src/main/icon.ts");
